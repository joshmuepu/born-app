#!/usr/bin/env node
/* Phase 1 reconciliation: merges the static census (source A), the runtime crawls (source B) and the manual (source C) into docs/qa/final-qa/coverage.md and prints every UNCOVERED item.
 * An item is covered when the crawl saw it on screen, or docs/qa/final-qa/exceptions.json carries evidence/reason for it. Exit code 1 while anything is uncovered. */
const fs = require('fs'), path = require('path')
const ROOT = path.join(__dirname, '..', '..')
const S = JSON.parse(fs.readFileSync(path.join(ROOT, 'qa-out', 'census-static.json'), 'utf8'))
const runtimes = fs.readdirSync(path.join(ROOT, 'qa-out')).filter((f) => /^census-runtime-.*\.json$/.test(f)).map((f) => JSON.parse(fs.readFileSync(path.join(ROOT, 'qa-out', f), 'utf8')))
const exFile = path.join(ROOT, 'docs/qa/final-qa/exceptions.json')
const EX = fs.existsSync(exFile) ? JSON.parse(fs.readFileSync(exFile, 'utf8')) : { anchors: {}, inventory: {} }
const seenText = runtimes.flatMap((r) => r.texts || []).map((t) => t.toLowerCase()).join('\n')
const states = runtimes.flatMap((r) => (r.states || []).map((s) => ({ ...s, crawl: r.profile })))
const sweepDirs = fs.readdirSync(path.join(ROOT, 'qa-out')).filter((d) => /^sweep-/.test(d))
const unc = []
const md = []
md.push('# Coverage matrix (generated by `scripts/qa/reconcile.cjs`)', '', `Generated ${new Date().toISOString()} · runtime crawls: ${runtimes.length} · distinct surfaces reached: ${states.length}`, '')
md.push('## 1. Surfaces reached by the runtime crawl (source B)', '', '| ID | Crawl | How to reach it | Headings / dialogs seen |', '|---|---|---|---|')
for (const s of states) md.push(`| ${s.crawl.replace('qa-', '')}:${s.id} | ${s.crawl} | ${s.path.join(' › ') || '(start)'} | ${[...(s.sig.heads || []).slice(0, 4), ...(s.sig.pop || [])].join('; ').replace(/\|/g, '/').slice(0, 90)} |`)
// inventory
md.push('', '## 2. Static inventory (source A) and where each item is proven', '', '| Kind | Item | Evidence / reason | Status |', '|---|---|---|---|')
const inv = (kind, item, autoSeen) => { const ev = EX.inventory[kind + ':' + item]; const ok = autoSeen || !!ev; md.push(`| ${kind} | ${item} | ${ev || (autoSeen ? 'seen by the runtime crawl' : '')} | ${ok ? 'covered' : '**UNCOVERED**'} |`); if (!ok) unc.push(kind + ': ' + item) }
for (const r of S.rail) inv('rail section', r, states.some((s) => (s.sig.rail || []).some((x) => x.toLowerCase().startsWith(r.slice(0, 4)))) )
for (const e of S.entries) inv('renderer entry', e, e === 'index.html')
for (const w of S.windows) inv('window', `${w.file}:${w.line}`, w.file === 'src/main/index.ts' && w.line < 720)
for (const k of S.settingsKeys) inv('setting', k, false)
for (const r of S.remote) inv('remote route', r, false)
for (const p of S.manual) inv('manual page', `${p.section} › ${p.title}`, false)
md.push('', '## 3. Declared UI strings (source A) never seen on screen by the crawl', '', 'Each needs either a targeted scenario that shows it (then it is covered by the sweep of that scenario) or a written reason in `exceptions.json`.', '', '| File | Kind | String | Status |', '|---|---|---|---|')
let nUnseen = 0
for (const a of S.anchors) {
  const t = a.text.toLowerCase()
  const seen = seenText.includes(t) || EX.anchors[a.text]
  if (!seen) { nUnseen++; unc.push('string: ' + a.file.replace('src/renderer/src/', '') + ' — ' + a.text); md.push(`| ${a.file.replace('src/renderer/src/', '')} | ${a.kind} | ${a.text.replace(/\|/g, '/')} | **UNCOVERED** |`) }
}
md.push('', `Declared strings: ${S.anchors.length}; seen or excepted: ${S.anchors.length - nUnseen}; uncovered: ${nUnseen}.`)
fs.mkdirSync(path.join(ROOT, 'docs/qa/final-qa'), { recursive: true })
fs.writeFileSync(path.join(ROOT, 'docs/qa/final-qa/coverage.md'), md.join('\n') + '\n')
fs.writeFileSync(path.join(ROOT, 'qa-out', 'uncovered.txt'), unc.join('\n'))
console.log(`surfaces ${states.length} · inventory uncovered+strings uncovered = ${unc.length}`)
if (process.argv.includes('--list')) console.log(unc.join('\n'))
process.exit(unc.length ? 1 : 0)
